#!/usr/bin/env bash
# connect-hermes.sh — print the ADB-over-WiFi connect command for Hermes mobile.
#
# Re-run this any time the WiFi IP changes. It writes the result to
# ~/.hermes/adb-connect.sh so Hermes mobile can read the current command.
#
# Usage:
#   bash connect-hermes.sh            # human-readable output + writes file
#   bash connect-hermes.sh --json     # machine-readable JSON
#   bash connect-hermes.sh --cmd      # print ONLY the `adb connect ...` line
set -euo pipefail

ADB_PORT="${ADB_PORT:-5555}"
OUT_FILE="${ADB_OUT_FILE:-$HOME/.hermes/adb-connect.sh}"

# Best heuristic for the LAN/egress IP on Android/Linux. Falls back to
# hostname -I, then to the first non-loopback IPv4 from `ip addr`.
get_ip() {
  local ip
  ip="$(ip route get 1.1.1.1 2>/dev/null | awk '{print $7; exit}' 2>/dev/null)"
  if [[ -z "$ip" ]]; then
    ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
  fi
  if [[ -z "$ip" ]]; then
    ip="$(ip -4 -o addr show 2>/dev/null | awk '$2!="lo"{print $4}' | cut -d/ -f1 | grep -v '^127\.' | head -1)"
  fi
  printf '%s' "$ip"
}

IP="$(get_ip)"
CMD="adb connect ${IP}:${ADB_PORT}"

case "${1:-}" in
  --cmd)
    printf '%s\n' "$CMD"
    ;;
  --json)
    printf '{"ip": "%s", "port": %s, "device": "%s", "command": "%s"}\n' \
      "$IP" "$ADB_PORT" "$IP:$ADB_PORT" "$CMD"
    ;;
  *)
    cat <<EOF
---------------- ADB over WiFi - connect to this device ----------------
  Device LAN IP : ${IP}
  ADB port      : ${ADB_PORT}
  Connect to    : ${IP}:${ADB_PORT}

  Run this command (on the machine running Hermes):
    adb connect ${IP}:${ADB_PORT}

  Then verify with:
    adb devices -l
-----------------------------------------------------------------------
EOF
    # Persist so Hermes mobile can read the current command.
    printf '#!/usr/bin/env bash\n# Auto-generated by connect-hermes.sh - run this to connect.\n# Regenerate with: bash connect-hermes.sh\n%s\n' "$CMD" > "$OUT_FILE"
    chmod +x "$OUT_FILE"
    echo "Saved: ${OUT_FILE}"
    ;;
esac
